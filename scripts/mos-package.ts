export const MOS_128_SCHEMA =
  "https://developer.microsoft.com/json-schemas/teams/v1.28/MicrosoftTeams.schema.json";
export const MOS_128_MANIFEST_VERSION = "1.28";
export const MOS_PACKAGE_FOLDER = "MOS Package";
export const README_MARKER = "<!-- generated by npm run mos:build; do not edit by hand -->";
const ROOT_FILES = new Set(["manifest.json", "color.png", "outline.png"]);

const require = createRequire(import.meta.url);
const SCHEMA_PATH = require.resolve(
  "@microsoft/app-manifest/build/json-schemas/teams/v1.28/MicrosoftTeams.schema.json",
);
export const APP_MANIFEST_VERSION = String(
  (JSON.parse(readFileSync(join(dirname(SCHEMA_PATH), "..", "..", "..", "..", "package.json"), "utf8")) as {
    version: string;
  }).version,
);

let validator: ReturnType<InstanceType<typeof Ajv04>["compile"]> | undefined;

/** Errors from the 1.28 schema bundled in @microsoft/app-manifest; empty when the manifest is valid. */
export function validateAgainst128Schema(manifest: unknown): string[] {
  if (!validator) {
    // Same clean-up as @microsoft/app-manifest's fetchSchema: "\a" is not a valid JS regex escape.
    const schema = JSON.parse(readFileSync(SCHEMA_PATH, "utf8").replace(/\\a/g, "\\x07"));
    const ajv = new Ajv04({ allErrors: true, strictTypes: false });
    addFormats(ajv, ["uri", "email", "regex"]);
    validator = ajv.compile(schema);
  }
  if (validator(manifest)) return [];
  return (validator.errors ?? []).map(
    (e) => `${e.instancePath || "/"} ${e.message ?? "is invalid"} ${JSON.stringify(e.params)}`,
  );
}

const sha = (data: Buffer) => createHash("sha256").update(data).digest("hex").toUpperCase();

/**
 * The 1.28 manifest text for a devPreview manifest: same keys in the same order, same indent and
 * line endings, with $schema and manifestVersion replaced and packageName removed.
 */
export function toManifest128(raw: string): string {
  const bom = raw.startsWith("\uFEFF") ? "\uFEFF" : "";
  const text = raw.slice(bom.length);
  const source = JSON.parse(text) as Record<string, unknown>;
  if (source.$schema !== MOS3_SCHEMA || source.manifestVersion !== MOS3_MANIFEST_VERSION) {
    throw new Error(
      `source manifest must be the evaluated devPreview manifest ($schema ${MOS3_SCHEMA}, manifestVersion ` +
        `${MOS3_MANIFEST_VERSION}); found ${String(source.$schema)} / ${String(source.manifestVersion)}`,
    );
  }
  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(source)) {
    if (key === "packageName") continue;
    out[key] = key === "$schema" ? MOS_128_SCHEMA : key === "manifestVersion" ? MOS_128_MANIFEST_VERSION : value;
  }
  const indent = /\n([ \t]+)"/.exec(text)?.[1] ?? "  ";
  const eol = text.includes("\r\n") ? "\r\n" : "\n";
  const trailing = /\r?\n$/.test(text) ? eol : "";
  return bom + JSON.stringify(out, null, indent).split("\n").join(eol) + trailing;
}

export type MosEntry = { name: string; bytes: number; sha256: string; sourceSha256: string };

export type MosDerivation = {
  zip: Buffer;
  sourceSha256: string;
  sha256: string;
  entries: MosEntry[];
  identicalEntries: number;
  manifest: Record<string, unknown>;
  removedPackageName: string;
  skillIcons: Array<{ folder: string; icon: string }>;
  checks: string[];
};

function readEntries(zipData: Buffer, label: string): Array<{ name: string; data: Buffer; timeval: number }> {
  const zip = new AdmZip(zipData);
  const seen = new Set<string>();
  return zip.getEntries().map((entry) => {
    const name = entry.entryName;
    const segments = name.split("/");
    if (entry.isDirectory) throw new Error(`${label} has a directory entry: ${name}`);
    if (name.includes("\\") || name.startsWith("/") || segments.some((s) => !s || s === "." || s === "..")) {
      throw new Error(`${label} has an unsafe entry name: ${name}`);
    }
    if (seen.has(name)) throw new Error(`${label} has a duplicate entry: ${name}`);
    seen.add(name);
    if (!ROOT_FILES.has(name) && segments[0] !== "skills") {
      throw new Error(`${label} has an unexpected entry outside manifest.json, the icons and skills/: ${name}`);
    }
    const data = entry.getData();
    if (crc32(data) >>> 0 !== entry.header.crc >>> 0) throw new Error(`${label} fails the CRC check for ${name}`);
    return { name, data, timeval: (entry.header as unknown as { timeval: number }).timeval };
  });
}

/** Derive the 1.28 package from an evaluated devPreview ZIP and prove the result. Throws on any failed check. */
export function deriveMos128Zip(sourceZip: Buffer): MosDerivation {
  const source = readEntries(sourceZip, "source ZIP");
  const sourceManifestEntry = source.find((e) => e.name === "manifest.json");
  if (!sourceManifestEntry) throw new Error("source ZIP has no manifest.json at its root");
  for (const icon of ["color.png", "outline.png"]) {
    if (!source.some((e) => e.name === icon)) throw new Error(`source ZIP has no ${icon} at its root`);
  }
  const sourceText = sourceManifestEntry.data.toString("utf8");
  const sourceManifest = JSON.parse(sourceText.replace(/^\uFEFF/, "")) as Record<string, unknown>;
  const manifestData = Buffer.from(toManifest128(sourceText), "utf8");

  const out = new AdmZip();
  for (const entry of source) out.addFile(entry.name, entry.name === "manifest.json" ? manifestData : entry.data);
  // Keep each entry's original DOS time; adm-zip's `time` setter would go through local time.
  out.getEntries().forEach((entry, i) => {
    (entry.header as unknown as { timeval: number }).timeval = source[i].timeval;
  });
  const zip = out.toBuffer();

  // Prove the written bytes, not the in-memory plan.
  const derived = readEntries(zip, "derived ZIP");
  const sourceNames = source.map((e) => e.name);
  const derivedNames = derived.map((e) => e.name);
  if (JSON.stringify(sourceNames) !== JSON.stringify(derivedNames)) {
    throw new Error("derived ZIP entry list differs from the source ZIP");
  }
  const entries: MosEntry[] = derived.map((e, i) => ({
    name: e.name,
    bytes: e.data.length,
    sha256: sha(e.data),
    sourceSha256: sha(source[i].data),
  }));
  const changed = entries.filter((e) => e.sha256 !== e.sourceSha256).map((e) => e.name);
  if (changed.some((name) => name !== "manifest.json")) {
    throw new Error(`entries other than manifest.json changed: ${changed.filter((n) => n !== "manifest.json").join(", ")}`);
  }

  const manifest = JSON.parse(derived.find((e) => e.name === "manifest.json")!.data.toString("utf8").replace(/^\uFEFF/, "")) as Record<string, unknown>;
  const expected = Object.fromEntries(
    Object.entries(sourceManifest)
      .filter(([key]) => key !== "packageName")
      .map(([key, value]) => [key, key === "$schema" ? MOS_128_SCHEMA : key === "manifestVersion" ? MOS_128_MANIFEST_VERSION : value]),
  );
  if (JSON.stringify(manifest) !== JSON.stringify(expected)) {
    throw new Error("derived manifest.json differs from the source in more than $schema, manifestVersion and packageName");
  }

  const schemaErrors = validateAgainst128Schema(manifest);
  if (schemaErrors.length) {
    throw new Error(`derived manifest.json fails the v1.28 schema:\n  ${schemaErrors.join("\n  ")}`);
  }

  const skillIcons = ((manifest.agentSkills ?? []) as Array<{ folder?: unknown }>).map(({ folder }) => {
    const rel = String(folder ?? "").replace(/^\.\//, "");
    const skill = derived.find((e) => e.name === `${rel}/SKILL.md`);
    if (!skill) throw new Error(`agentSkills folder ${String(folder)} has no SKILL.md in the package`);
    const metadata = parseFrontmatter(skill.data.toString("utf8")).data.metadata as Record<string, unknown> | undefined;
    return { folder: posix.basename(rel), icon: String(metadata?.icon ?? "(none)") };
  });

  const identicalEntries = entries.length - 1;
  return {
    zip,
    sourceSha256: sha(sourceZip),
    sha256: sha(zip),
    entries,
    identicalEntries,
    manifest,
    removedPackageName: String(sourceManifest.packageName ?? "(absent)"),
    skillIcons,
    checks: [
      "every entry of the source ZIP and the derived ZIP passes its CRC-32 check",
      `source manifest is devPreview ($schema ${MOS3_SCHEMA}, manifestVersion ${MOS3_MANIFEST_VERSION})`,
      "entries sit at the ZIP root: manifest.json, color.png, outline.png and skills/ only; no directory entries, duplicates or unsafe names",
      `entry list identical to the source: ${entries.length} entries, same names, same order, same timestamps`,
      `${identicalEntries} of ${entries.length} entries byte-identical to the evaluated ZIP (SHA-256); only manifest.json differs`,
      "manifest.json differs only in $schema (v1.28 URL), manifestVersion (1.28) and packageName (removed); every other field and the key order are unchanged",
      `manifest validates against the local v1.28 MicrosoftTeams.schema.json (@microsoft/app-manifest ${APP_MANIFEST_VERSION}), errors: none`,
      `every agentSkills folder has a SKILL.md in the package (${skillIcons.length} skills)`,
    ],
  };
}

/** The body of a `## <heading>` section of listing-metadata.md, or undefined. */
export function listingSection(markdown: string, heading: string): string | undefined {
  const lines = markdown.replace(/\r\n/g, "\n").split("\n");
  const start = lines.findIndex((line) => line.trim().toLowerCase() === `## ${heading}`.toLowerCase());
  if (start < 0) return undefined;
  const end = lines.findIndex((line, i) => i > start && /^##\s/.test(line));
  return lines.slice(start + 1, end < 0 ? undefined : end).join("\n").trim() || undefined;
}

export type MosReadmeInput = {
  displayName: string;
  slug: string;
  version: string;
  packageFile: string;
  sourceLabel: string;
  promotedLabel?: string;
  listing?: string;
  listingVersion?: string;
  derivation: MosDerivation;
};

export function renderMosReadme(input: MosReadmeInput): string {
  const { derivation: d, listing } = input;
  const m = d.manifest as {
    id?: string;
    version?: string;
    manifestVersion?: string;
    accentColor?: string;
    name?: { short?: string; full?: string };
    description?: { short?: string; full?: string };
  };
  const field = (label: string, value: string | undefined, max: number) =>
    `| ${label} | ${(value ?? "").replace(/\|/g, "\\|")} | ${(value ?? "").length} / ${max} |`;
  const section = (heading: string) => (listing ? listingSection(listing, heading) : undefined) ?? "_Not in listing-metadata.md._";
  const lines = [
    README_MARKER,
    `# ${input.displayName} - MOS package (manifest 1.28) v${input.version}`,
    "",
    `Package: \`${input.packageFile}\` (${d.zip.length.toLocaleString("en-US")} bytes, SHA-256 \`${d.sha256}\`).`,
    "",
    `Derived from the Cowork-evaluated ZIP \`${input.sourceLabel}\` (SHA-256 \`${d.sourceSha256}\`).` +
      (input.promotedLabel ? ` \`${input.promotedLabel}\` is byte-identical to it.` : ""),
    "",
    "Only `manifest.json` differs from the evaluated ZIP. Cowork evaluated the devPreview manifest; this package carries " +
      "the 1.28 manifest the store submission needs (owner decision 2026-10-16 in `docs/professional-services/wave-1.md`). " +
      "It keeps the same app id, so do not install this package and the evaluated package in the same tenant.",
    "",
    "## Listing",
    "",
    "| Field | Value | Chars |",
    "|---|---|---|",
    field("name.short", m.name?.short, 30),
    field("name.full", m.name?.full, 100),
    field("description.short", m.description?.short, 80),
    `| description.full | see below | ${(m.description?.full ?? "").length} / 4000 |`,
    "",
    "description.full:",
    "",
    "```text",
    m.description?.full ?? "",
    "```",
    "",
    "### Category and industry",
    "",
    section("Category and industry"),
    "",
    "### Top 3 prompts",
    "",
    section("Top 3 prompts"),
    "",
    "### Connectors (priority order)",
    "",
    section("Connectors (priority order)"),
    "",
    "### Icons",
    "",
    `Plugin icons: \`color.png\` and \`outline.png\` (byte-identical to the evaluated ZIP). accentColor: \`${m.accentColor ?? ""}\`.`,
    "",
    "| Skill folder | SKILL.md metadata.icon |",
    "|---|---|",
    ...d.skillIcons.map((s) => `| ${s.folder} | ${s.icon} |`),
    "",
    "Listing icon IDs from `listing-metadata.md`:",
    "",
    section("Icons"),
    "",
  ];
  if (input.listingVersion && input.listingVersion !== input.version) {
    lines.push(
      `> The listing sections above come from the repository's \`listing-metadata.md\` for plugin version ${input.listingVersion}, not ${input.version}. Check them before submission.`,
      "",
    );
  }
  lines.push(
    "## Manifest",
    "",
    `- id: \`${m.id ?? ""}\` (unchanged from the evaluated ZIP)`,
    `- version: ${m.version ?? ""}; manifestVersion: ${m.manifestVersion ?? ""}`,
    `- $schema: ${MOS_128_SCHEMA}`,
    `- packageName removed (was \`${d.removedPackageName}\`; the 1.28 schema does not allow it)`,
    `- agentSkills: ${d.skillIcons.map((s) => s.folder).join(", ")}`,
    "",
    "## What was checked",
    "",
    ...d.checks.map((check) => `- ${check}`),
    "",
    "## Entries",
    "",
    "| Entry | Bytes | SHA-256 | Same as evaluated ZIP |",
    "|---|---|---|---|",
    ...d.entries.map((e) => `| ${e.name} | ${e.bytes} | \`${e.sha256}\` | ${e.sha256 === e.sourceSha256 ? "yes" : "no (1.28 manifest)"} |`),
    "",
    "`skills\\` next to this README is an extracted copy of the package's `skills/` folder for reviewers.",
    "",
  );
  return lines.join("\n");
}

export type BuildMosOptions = {
  slug: string;
  version?: string;
  sharepointRoot: string;
  outDir?: string;
  repoRoot?: string;
};

export type BuildMosResult = {
  outDir: string;
  packagePath: string;
  status: "written" | "unchanged";
  derivation: MosDerivation;
};

/**
 * Build `<plugin folder>\MOS Package\` from the archived evaluated ZIP. Writing into the plugin folder
 * requires the C4 promotion (`<slug>-cowork.zip` byte-identical to the evaluated ZIP); `outDir` writes
 * outside the SharePoint library for a dry run. Nothing is deleted: a different same-version ZIP, a
 * hand-written README, stale files under `skills\` or a file/folder clash stop the build before
 * anything is written.
 */
export function buildMosPackage(options: BuildMosOptions): BuildMosResult {
  const submission = findSubmission(options.slug, options.repoRoot ?? ROOT);
  if (submission.packageFormat !== "mos3") {
    throw new Error(`${submission.slug} is not a MOS3 submission; only MOS3 plugins get a derived MOS package`);
  }
  const version = options.version ?? submission.version;
  const { slug, industry } = submission;
  const archiveDir = evaluationArchiveDir(options.sharepointRoot, industry, slug, version);
  const sourcePath = join(archiveDir, `${slug}.zip`);
  if (!existsSync(sourcePath)) throw new Error(`no archived evaluated ZIP at ${sourcePath}`);
  const sourceZip = readFileSync(sourcePath);
  const derivation = deriveMos128Zip(sourceZip);
  if (derivation.manifest.version !== version) {
    throw new Error(`evaluated manifest version ${String(derivation.manifest.version)} does not match ${version}`);
  }

  const pluginDir = sharepointPluginDir(options.sharepointRoot, industry, slug);
  let promotedLabel: string | undefined;
  let outDir = options.outDir;
  if (outDir && isInside(realPathOf(outDir), realPathOf(options.sharepointRoot))) {
    throw new Error(
      `--out-dir ${outDir} is inside the SharePoint library. Omit --out-dir to write the plugin's ` +
        `${MOS_PACKAGE_FOLDER} folder after the C4 promotion; dry runs go outside the library.`,
    );
  }
  if (!outDir) {
    if (!usesRetailLayout(industry, slug)) {
      throw new Error(`${slug} is not filed in the Retail layout (SHAREPOINT_WAVES); pass --out-dir to build elsewhere`);
    }
    const promoted = join(pluginDir, `${slug}-cowork.zip`);
    if (!existsSync(promoted)) {
      throw new Error(
        `${promoted} does not exist. Build the MOS package only after human review sign-off (C2) and the C4 promotion; ` +
          "pass --out-dir for a dry run.",
      );
    }
    if (sha(readFileSync(promoted)) !== derivation.sourceSha256) {
      throw new Error(`${promoted} is not byte-identical to the evaluated ZIP for v${version}; refusing to build`);
    }
    promotedLabel = `${slug}-cowork.zip`;
    outDir = join(pluginDir, MOS_PACKAGE_FOLDER);
  }

  const packageFile = `${slug}-mos3-v${version}.zip`;
  const packagePath = join(outDir, packageFile);
  const readmePath = join(outDir, "README.md");
  const skillsDir = join(outDir, "skills");

  // Preflight: everything that can refuse runs before the first write.
  if (existsSync(outDir) && !statSync(outDir).isDirectory()) throw new Error(`${outDir} is not a folder`);
  let status: BuildMosResult["status"] = "written";
  assertFileTarget(outDir, [packageFile]);
  if (existsSync(packagePath)) {
    if (sha(readFileSync(packagePath)) !== derivation.sha256) {
      throw new Error(`${packagePath} already exists with different content; the owner must move it aside first`);
    }
    status = "unchanged";
  }
  assertFileTarget(outDir, ["README.md"]);
  if (existsSync(readmePath) && !readFileSync(readmePath, "utf8").includes(README_MARKER)) {
    throw new Error(`${readmePath} was not generated by mos:build; the owner must move it aside first`);
  }
  const skillEntries = derivation.entries.filter((e) => e.name.startsWith("skills/"));
  for (const entry of skillEntries) assertFileTarget(outDir, entry.name.split("/"));
  if (existsSync(skillsDir)) {
    const wanted = new Set(skillEntries.map((e) => e.name.slice("skills/".length)));
    const walk = walkNoFollow(skillsDir);
    const stale = [...walk.files.filter((rel) => !wanted.has(rel)), ...walk.symlinks];
    if (stale.length) {
      throw new Error(
        `${skillsDir} holds files that are not in this package; the owner must remove them first:\n  ${stale.join("\n  ")}`,
      );
    }
  }
  const listingPath = join(submission.dir, "listing-metadata.md");
  const listing = existsSync(listingPath) ? readFileSync(listingPath, "utf8") : undefined;
  const readme = renderMosReadme({
    displayName: submission.displayName,
    slug,
    version,
    packageFile,
    sourceLabel: relative(options.sharepointRoot, sourcePath).split(sep).join("\\"),
    promotedLabel,
    listing,
    listingVersion: listing ? submission.version : undefined,
    derivation,
  });

  // Skills first and the ZIP last, so a failed run never leaves a new ZIP beside a partial folder.
  mkdirSync(outDir, { recursive: true });
  const zip = new AdmZip(derivation.zip);
  for (const entry of skillEntries) {
    const target = join(outDir, ...entry.name.split("/"));
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, zip.getEntry(entry.name)!.getData());
  }
  if (status === "written") {
    const partial = `${packagePath}.partial`;
    writeFileSync(partial, derivation.zip);
    if (sha(readFileSync(partial)) !== derivation.sha256) {
      rmSync(partial, { force: true });
      throw new Error("written MOS package failed hash verification");
    }
    renameSync(partial, packagePath);
  }
  writeFileSync(readmePath, readme, "utf8");
  return { outDir, packagePath, status, derivation };
}

/** The real path of `path`, resolving links in its longest existing prefix. */
function realPathOf(path: string): string {
  let current = resolve(path);
  const rest: string[] = [];
  while (!existsSync(current)) {
    const parent = dirname(current);
    if (parent === current) break;
    rest.unshift(basename(current));
    current = parent;
  }
  return join(existsSync(current) ? realpathSync.native(current) : current, ...rest);
}

function isInside(child: string, parent: string): boolean {
  const norm = (p: string) => (process.platform === "win32" ? p.toLowerCase() : p);
  const rel = relative(norm(parent), norm(child));
  return rel === "" || (!rel.startsWith("..") && !isAbsolute(rel));
}

/** Refuse when a path under `root` would land on a link, or on a folder where a file goes (or vice versa). */
function assertFileTarget(root: string, segments: string[]): void {
  let current = root;
  segments.forEach((segment, i) => {
    current = join(current, segment);
    let stat;
    try {
      stat = lstatSync(current);
    } catch {
      return;
    }
    const last = i === segments.length - 1;
    if (stat.isSymbolicLink() || (last ? !stat.isFile() : !stat.isDirectory())) {
      throw new Error(`${current} is not a ${last ? "regular file" : "folder"}; the owner must move it aside first`);
    }
  });
}
