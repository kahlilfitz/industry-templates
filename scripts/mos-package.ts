/**
 * Derived manifest-1.28 MOS package (owner decision 2026-10-16, docs/professional-services/wave-1.md).
 *
 * Cowork evaluates the devPreview package. The store-facing 1.28 package is derived from that exact
 * evaluated ZIP: only manifest.json changes ($schema, manifestVersion, packageName removed), every
 * other entry is copied byte for byte, and the result is proven and validated before it is written.
 */
